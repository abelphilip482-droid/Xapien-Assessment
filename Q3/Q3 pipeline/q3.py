# ============================================================

GARMENT_OUTPUT_DIR = GARMENT_MASK_DIR

garment_files = sorted([
    f for f in os.listdir(GARMENT_DIR)
    if f.lower().endswith((".png", ".jpg", ".jpeg"))
])

for filename in garment_files:

    print("\n" + "=" * 70)
    print("PROCESSING GARMENT:", filename)
    print("=" * 70)

    garment_path = os.path.join(GARMENT_DIR, filename)
    garment = Image.open(garment_path).convert("RGB")

    # --------------------------------------------------------
    # Detect garment
    # --------------------------------------------------------

    garment_inputs = dino_processor(
        images=garment,
        text="shirt. t-shirt. top. blouse. dress. jacket. garment.",
        return_tensors="pt"
    )

    garment_inputs = {
        k: v.to(device) if hasattr(v, "to") else v
        for k, v in garment_inputs.items()
    }

    with torch.no_grad():
        garment_outputs = dino_model(**garment_inputs)

    garment_results = dino_processor.post_process_grounded_object_detection(
        garment_outputs,
        garment_inputs["input_ids"],
        target_sizes=[garment.size[::-1]]
    )[0]

    if len(garment_results["boxes"]) == 0:
        print("❌ No garment detected")
        continue

    best_idx = int(torch.argmax(garment_results["scores"]))

    garment_box = (
        garment_results["boxes"][best_idx]
        .detach()
        .cpu()
        .tolist()
    )

    garment_score = float(
        garment_results["scores"][best_idx]
    )

    print(
        f"Garment box: {garment_box} "
        f"(score={garment_score:.3f})"
    )

    # --------------------------------------------------------
    # Segment detected garment with SAM
    # --------------------------------------------------------

    sam_input = sam_processor(
        images=garment,
        input_boxes=[[garment_box]],
        return_tensors="pt"
    )

    sam_input = {
        k: v.to(device) if hasattr(v, "to") else v
        for k, v in sam_input.items()
    }

    with torch.no_grad():
        sam_output = sam_model(**sam_input)

    processed_masks = (
        sam_processor.image_processor.post_process_masks(
            sam_output.pred_masks.cpu(),
            sam_input["original_sizes"].cpu(),
            sam_input["reshaped_input_sizes"].cpu()
        )
    )

    garment_mask = (
        processed_masks[0][0][0]
        .numpy()
        .astype(np.uint8)
    )

    # --------------------------------------------------------
    # Save binary mask
    # --------------------------------------------------------

    mask_image = Image.fromarray(
        garment_mask * 255
    )

    output_name = (
        os.path.splitext(filename)[0] + ".png"
    )

    output_path = os.path.join(
        GARMENT_OUTPUT_DIR,
        output_name
    )

    mask_image.save(output_path)

    print(
        f"✅ Garment mask saved: {output_path}"
    )

    print(
        f"Mask pixels: {int(garment_mask.sum()):,}"
    )

print("\n" + "=" * 70)
print("GARMENT MASK GENERATION COMPLETE")
print("=" * 70)

print(
    "Files:",
    sorted(os.listdir(GARMENT_OUTPUT_DIR))
)

