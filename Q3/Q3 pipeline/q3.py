person_inputs = dino_processor(
    images=image,
    text="person.",
    return_tensors="pt"
)

person_inputs = {
    k: v.to(device) if hasattr(v, "to") else v
    for k, v in person_inputs.items()
}

with torch.no_grad():
    person_outputs = dino_model(**person_inputs)

person_results = dino_processor.post_process_grounded_object_detection(
    person_outputs,
    person_inputs["input_ids"],
    target_sizes=[image.size[::-1]]
)[0]

if len(person_results["boxes"]) == 0:
    raise RuntimeError("No person detected.")

best_person_idx = int(torch.argmax(person_results["scores"]))

person_box = (
    person_results["boxes"][best_person_idx]
    .detach()
    .cpu()
    .tolist()
)

person_score = float(
    person_results["scores"][best_person_idx]
)

print(
    f"Person box: {person_box} "
    f"(score={person_score:.3f})"
)

# ------------------------------------------------------------
# PERSON MASK — SAM
# ------------------------------------------------------------

sam_person_input = sam_processor(
    images=image,
    input_boxes=[[person_box]],
    return_tensors="pt"
)

sam_person_input = {
    k: v.to(device) if hasattr(v, "to") else v
    for k, v in sam_person_input.items()
}

with torch.no_grad():
    sam_person_output = sam_model(**sam_person_input)

person_masks_processed = (
    sam_processor.image_processor.post_process_masks(
        sam_person_output.pred_masks.cpu(),
        sam_person_input["original_sizes"].cpu(),
        sam_person_input["reshaped_input_sizes"].cpu()
    )
)

person_mask = (
    person_masks_processed[0][0][0]
    .numpy()
    .astype(bool)
)

