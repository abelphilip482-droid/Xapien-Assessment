boxes = []
scores = []
filtered_labels = []

for conf_threshold in CONF_THRESHOLDS_TO_TRY:

    inputs = dino_processor(
        images=image,
        text=text_prompt,
        return_tensors="pt"
    )

    inputs = {
        k: v.to(device) if hasattr(v, "to") else v
        for k, v in inputs.items()
    }

    with torch.no_grad():
        outputs = dino_model(**inputs)

    results = dino_processor.post_process_grounded_object_detection(
        outputs,
        inputs["input_ids"],
        target_sizes=[image.size[::-1]]
    )[0]

    detected_labels = results.get("text_labels", None)

    if detected_labels is None:
        detected_labels = [
            str(l)
            for l in results.get("labels", [])
        ]

    keep = [
        i
        for i, s in enumerate(results["scores"])
        if float(s) >= conf_threshold
    ]

    if keep:
        boxes = [results["boxes"][i] for i in keep]
        scores = [results["scores"][i] for i in keep]
        filtered_labels = [
            detected_labels[i]
            for i in keep
        ]

        print(
            f"✅ Detections at "
            f"threshold={conf_threshold}: "
            f"{len(boxes)}"
        )

        break

    else:
        print(
            f"⚠️ No detections at "
            f"threshold={conf_threshold}, "
            f"retrying lower..."
        )

# ------------------------------------------------------------
# PRINT DETECTIONS
# ------------------------------------------------------------

for i in range(len(boxes)):

    print(
        f"  {filtered_labels[i]:15s} "
        f"score={float(scores[i]):.3f} "
        f"box={[round(x,1) for x in boxes[i].detach().cpu().tolist()]}"
    )

# ------------------------------------------------------------
# SEMANTIC MASKS VIA SAM
# ------------------------------------------------------------

semantic_masks = {}

for semantic_class, candidate_labels in semantic_candidates.items():

    candidate_indices = []

    for i, detected_label in enumerate(filtered_labels):

        detected_lower = (
            str(detected_label)
            .lower()
            .strip()
        )

        for candidate in candidate_labels:

            candidate_lower = (
                candidate.lower()
                .strip()
            )

            if (
                detected_lower == candidate_lower
                or candidate_lower in detected_lower
                or detected_lower in candidate_lower
            ):
                candidate_indices.append(i)
                break

    candidate_indices = list(
        dict.fromkeys(candidate_indices)
    )

    if not candidate_indices:
        print(
            f"  ⚠️ No detection for "
            f"{semantic_class}"
        )
        continue

    best_idx = max(
        candidate_indices,
        key=lambda i: float(scores[i])
    )

    box = (
        boxes[best_idx]
        .detach()
        .cpu()
        .tolist()
    )

    best_score = float(scores[best_idx])

    sam_input = sam_processor(
        images=image,
        input_boxes=[[box]],
        return_tensors="pt"
    )

    sam_input = {
        k: v.to(device) if hasattr(v, "to") else v
        for k, v in sam_input.items()
    }

    with torch.no_grad():
        sam_output = sam_model(**sam_input)

    processed_masks = (
        sam_processor.image_processor.post_process_masks(
            sam_output.pred_masks.cpu(),
            sam_input["original_sizes"].cpu(),
            sam_input["reshaped_input_sizes"].cpu()
        )
    )

    mask = (
        processed_masks[0][0][0]
        .numpy()
        .astype(bool)
    )

    semantic_masks[semantic_class] = mask

    print(
        f"  ✅ {semantic_class:15s} "
        f"score={best_score:.3f} "
        f"pixels={int(mask.sum()):,}"
    )

# ------------------------------------------------------------
# PARSING MAP
